import { mkdir, writeFile } from 'node:fs/promises';
import { registry } from '../lib/data/registry';
import { validateRegistry } from '../lib/contract/validate';
import { resolveTokens, cssVariables } from '../lib/theme/resolve';
const system = validateRegistry(registry);
await mkdir('lib/generated', { recursive: true });
const imports = system.components.map((c, i) => `import { ${c.publicImport.exportName} as C${i} } from ${JSON.stringify(c.publicImport.module)};`);
const previewKeys = system.examples.filter(e => e.intent === 'recommended').map(e => `previewMap[${JSON.stringify(e.previewKey)}]`);
const layoutKeys = system.layouts.map(l => `layoutPreviewMap[${JSON.stringify(l.previewKey)}]`);
// The portal API is verified against the installed declarations, before M2 uses it.
await writeFile('lib/generated/public-contracts.ts', [
  '// Generated by scripts/generate.ts. Do not edit.', ...imports,
  'import { previewMap, layoutPreviewMap } from "@/components/examples/previews";',
  'import type { ComponentProps } from "react";',
  'import { UNSAFE_PortalProvider } from "@react-aria/overlays";',
  `export const verifiedPublicSymbols = [${system.components.map((_, i) => `C${i}`).join(', ')}];`,
  `export const verifiedPreviews = [${[...previewKeys, ...layoutKeys].join(', ')}];`,
  'export const verifiedPortalProvider = UNSAFE_PortalProvider;',
  'export const verifiedPortalContainer: NonNullable<ComponentProps<typeof UNSAFE_PortalProvider>["getContainer"]> = () => null;',
  'void layoutPreviewMap;',
].join('\n') + '\n');
const theme = system.themePresets.find(t => t.id === system.defaultThemeId)!;
const resolved = resolveTokens(system.tokens, theme, system.fonts);
const declaration = (mode: 'light' | 'dark') => Object.entries(cssVariables(resolved, mode)).map(([key, value]) => `  ${key}: ${value};`).join('\n');
await writeFile('app/tokens.css', `/* Generated from the default preset. */\n:root {\n${declaration('light')}\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n${declaration('dark')}\n  }\n}\n`);
console.log(`Validated ${system.components.length} components, ${system.tokens.length} tokens, ${system.rules.length} rules, and ${system.examples.length} examples.`);
