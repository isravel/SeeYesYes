import { mkdir, writeFile } from 'node:fs/promises';
import { registry, defaultTheme } from '../lib/data/registry';
import { createContext } from '../lib/contract/context';
import { byteLength } from '../lib/contract/export-files';
import { contextMarkdown, stableJson } from '../lib/contract/serialize';

const settings = { settingsVersion: 1 as const, theme: defaultTheme, appearance: 'system' as const };
const row = (label: string, context: ReturnType<typeof createContext>) => `| ${label} | ${byteLength(stableJson(context)).toLocaleString('en-US')} | ${byteLength(contextMarkdown(context)).toLocaleString('en-US')} |`;
const fixtures = ['spinner', 'button', 'dialog', 'tabs', 'table'];
const lines = [
  '# Export size comparison', '',
  'Generated by `npm run report:sizes` from the registry and default theme. Sizes are UTF-8 bytes, not token counts. They show how big each export is, not how well an agent performs with it.', '',
  '| Export | JSON bytes | Markdown bytes |', '| --- | ---: | ---: |',
  row('Overview', createContext(registry, { mode: 'overview', settings })),
  ...fixtures.map(id => row(`Task: ${id}`, createContext(registry, { mode: 'task', componentIds: [id], settings }))),
  row('Full', createContext(registry, { mode: 'full', settings })), '',
];
await mkdir('docs/evidence/M5/M5.8', { recursive: true });
await writeFile('docs/evidence/M5/M5.8/export-sizes.md', lines.join('\n'));
console.log(lines.join('\n'));
