import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { registry } from '@/lib/data/registry';
import { componentReadiness } from '@/lib/contract/readiness';

const roles: Record<string, string> = {
  button: 'button', link: 'link', input: 'textbox', textarea: 'textbox', select: 'combobox', checkbox: 'checkbox', 'radio-group': 'radio',
  switch: 'switch', dialog: 'button', 'dropdown-menu': 'button', tabs: 'tab', tooltip: 'button', navigation: 'link',
  'empty-state': 'button', 'error-state': 'button', 'not-found': 'link', 'copy-button': 'button',
};
const allowedStops: Record<string, string[]> = { table: ['region'], 'form-field': ['input'] };
const forcedState: Record<string, string> = { 'empty-state': 'action' };
const focusableInside = 'a[href], button, input, select, textarea, summary, [tabindex]:not([tabindex="-1"])';

async function openDemo(page: Page, id: string, name: string) {
  await page.goto(`/components/${id}`);
  const preview = page.getByTestId('component-preview');
  await expect(preview).toBeVisible({ timeout: 15_000 });
  if (forcedState[id]) await page.getByRole('combobox', { name: `${name} state`, exact: true }).selectOption(forcedState[id]);
  return preview;
}

/** Start just before the preview and Tab until focus lands inside it. */
async function tabIntoPreview(page: Page) {
  await page.getByRole('heading', { level: 2, name: 'Live preview', exact: true }).evaluate(el => { el.setAttribute('tabindex', '-1'); (el as HTMLElement).focus(); });
  for (let presses = 0; presses < 10; presses += 1) {
    await page.keyboard.press('Tab');
    if (await page.locator('[data-testid="component-preview"] :focus').count()) return presses + 1;
  }
  return 0;
}

const hasFocusIndicator = (page: Page) => page.evaluate(() => {
  const visible = (el: Element | null) => {
    if (!el) return false;
    const style = getComputedStyle(el);
    return (style.outlineStyle !== 'none' && parseFloat(style.outlineWidth) > 0) || style.boxShadow !== 'none';
  };
  const el = document.activeElement as HTMLElement;
  const candidates = [el, el.parentElement, el.nextElementSibling, el.previousElementSibling, el.closest('label'), el.closest('[data-focus-visible]')];
  return el.matches(':focus-visible') && candidates.some(visible);
});

test('every interactive component is reachable by Tab, named, and shows a visible focus indicator', async ({ page }) => {
  test.setTimeout(180_000);
  const rows: string[] = [];
  const interactive = registry.components.filter(component => component.interactive);
  expect(interactive.map(c => c.id).sort()).toEqual(Object.keys(roles).sort());
  for (const component of registry.components) {
    const preview = await openDemo(page, component.id, component.name);
    const readiness = componentReadiness(component, registry);
    let reach = '—', named = '—', focus = '—';
    if (component.interactive) {
      const presses = await tabIntoPreview(page);
      expect(presses, `${component.id} should be reachable by Tab`).toBeGreaterThan(0);
      const focused = page.locator('[data-testid="component-preview"] :focus');
      await expect(focused, `${component.id} role`).toHaveRole(roles[component.id] as 'button');
      await expect(focused, `${component.id} accessible name`).toHaveAccessibleName(/\S/);
      expect(await hasFocusIndicator(page), `${component.id} focus indicator`).toBe(true);
      [reach, named, focus] = ['yes', 'yes', 'yes'];
    } else {
      // Non-interactive components add no tab stops of their own. The exceptions are the scrollable Table region, which must be
      // keyboard reachable, and the Input that the Form Field demo wraps (the field itself adds no stop).
      const stops = await preview.locator(focusableInside).evaluateAll(els => els.map(el => el.getAttribute('role') ?? el.tagName.toLowerCase()));
      expect(stops, `${component.id} tab stops`).toEqual(allowedStops[component.id] ?? []);
      if (component.id === 'table') { reach = 'scroll region'; focus = 'yes'; }
      if (component.id === 'form-field') reach = 'wrapped input only';
    }
    rows.push(`| ${component.name} | ${component.interactive ? 'yes' : 'no'} | ${readiness.complete ? 'yes' : 'NO'} | ${reach} | ${named} | ${focus} | ${component.accessibility.keyboard.map(k => k.key).join('; ') || '—'} | ${component.accessibility.status === 'reviewed' ? 'reviewed' : 'not reviewed'} |`);
  }
  mkdirSync('docs/evidence/M4/M4.7', { recursive: true });
  writeFileSync('docs/evidence/M4/M4.7/component-review-matrix.md', [
    '# Component review matrix (automated)', '',
    'Generated by `tests/browser/keyboard-matrix.spec.ts` against the production build. It records what the automated keyboard run observed. It is not a human accessibility review: every component is still "not reviewed".', '',
    '| Component | Interactive | Metadata-complete | Reachable by Tab | Accessible name | Visible focus | Contract keys | Review status |', '| --- | --- | --- | --- | --- | --- | --- | --- |', ...rows, '',
  ].join('\n'));
});

test('native controls respond to the keys their contracts list', async ({ page }) => {
  // Checkbox and Switch: Space toggles.
  for (const [id, name, role] of [['checkbox', 'Checkbox', 'checkbox'], ['switch', 'Switch', 'switch']] as const) {
    await openDemo(page, id, name);
    await tabIntoPreview(page);
    const control = page.locator('[data-testid="component-preview"] :focus');
    const before = await control.isChecked();
    await page.keyboard.press('Space');
    expect(await control.isChecked(), `${role} Space`).toBe(!before);
    await page.keyboard.press('Space');
    expect(await control.isChecked()).toBe(before);
  }

  // Radio group: arrow keys move the selection within one named group.
  await openDemo(page, 'radio-group', 'RadioGroup');
  await tabIntoPreview(page);
  const first = page.locator('[data-testid="component-preview"] :focus');
  await expect(first).not.toBeChecked();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByTestId('component-preview').getByRole('radio', { checked: true })).toHaveCount(1);
  const picked = await page.getByTestId('component-preview').getByRole('radio', { checked: true }).getAttribute('value');
  await page.keyboard.press('ArrowDown');
  await expect(page.getByTestId('component-preview').getByRole('radio', { checked: true })).toHaveCount(1);
  expect(await page.getByTestId('component-preview').getByRole('radio', { checked: true }).getAttribute('value')).not.toBe(picked);

  // Select: arrow keys change the native value.
  await openDemo(page, 'select', 'Select');
  await tabIntoPreview(page);
  const select = page.locator('[data-testid="component-preview"] select');
  await expect(select).toHaveValue('editor');
  // A native select: type-ahead changes the value from the keyboard without opening the list. Arrow-key behavior is the
  // platform's own (some platforms open the list), so it is not asserted here.
  await page.keyboard.press('v');
  await expect(select).toHaveValue('viewer');
  await expect(select).toBeFocused();

  // Input and Textarea: typing enters text.
  for (const [id, name] of [['input', 'Input'], ['textarea', 'Textarea']] as const) {
    await openDemo(page, id, name);
    await tabIntoPreview(page);
    await page.keyboard.type('hello');
    await expect(page.locator('[data-testid="component-preview"] :focus')).toHaveValue('hello');
  }

  // Link: Enter follows it.
  await openDemo(page, 'link', 'Link');
  await tabIntoPreview(page);
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/\/components$/);

  // Button: Enter and Space both activate a native button.
  await openDemo(page, 'button', 'Button');
  await page.getByTestId('component-preview').getByRole('button').evaluate(el => { (window as unknown as { presses: number }).presses = 0; el.addEventListener('click', () => { (window as unknown as { presses: number }).presses += 1; }); });
  await tabIntoPreview(page);
  await page.keyboard.press('Enter');
  await page.keyboard.press('Space');
  expect(await page.evaluate(() => (window as unknown as { presses: number }).presses)).toBe(2);
});

test('Dialog, Dropdown Menu, Tabs, and Tooltip keep their keyboard behavior in their own previews', async ({ page }) => {
  // Dialog: Enter opens, focus stays inside, Escape closes and restores focus to the trigger.
  await openDemo(page, 'dialog', 'Dialog');
  await tabIntoPreview(page);
  const trigger = page.getByRole('button', { name: 'Open settings' });
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog', { name: 'Preview settings' });
  await expect(dialog).toBeVisible();
  for (let i = 0; i < 4; i += 1) { await page.keyboard.press('Tab'); expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true); }
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(trigger).toBeFocused();

  // Dropdown Menu: ArrowDown opens, arrows move, Escape closes and restores focus.
  await openDemo(page, 'dropdown-menu', 'DropdownMenu');
  await tabIntoPreview(page);
  const menuTrigger = page.getByRole('button', { name: 'Actions' });
  await page.keyboard.press('ArrowDown');
  const menu = page.getByRole('menu');
  await expect(menu).toBeVisible();
  await expect(page.getByRole('menuitem').first()).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('menuitem').nth(1)).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(menu).toHaveCount(0);
  await expect(menuTrigger).toBeFocused();

  // Tabs: arrow keys move focus and selection (automatic activation); each tab controls a panel.
  await openDemo(page, 'tabs', 'Tabs');
  await tabIntoPreview(page);
  const tabs = page.getByRole('tab');
  await expect(tabs.first()).toHaveAttribute('aria-selected', 'true');
  await page.keyboard.press('ArrowRight');
  await expect(tabs.nth(1)).toBeFocused();
  await expect(tabs.nth(1)).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('tabpanel')).toBeVisible();
  await page.keyboard.press('Home');
  await expect(tabs.first()).toBeFocused();

  // Tooltip: appears on keyboard focus and Escape dismisses it.
  await openDemo(page, 'tooltip', 'Tooltip');
  await tabIntoPreview(page);
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
});
